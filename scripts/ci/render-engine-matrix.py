"""Render build/conformance/*.json (written by the engine test targets) into the parity matrix in
checklists/005-browser-engine.md, between the conformance-matrix markers.

  render-engine-matrix.py          rewrite the matrix
  render-engine-matrix.py --check  fail if the checklist is out of date (CI)
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
REPORTS = ROOT / "build" / "conformance"
CHECKLIST = ROOT / "checklists" / "005-browser-engine.md"
BEGIN, END = "<!-- conformance-matrix:begin -->", "<!-- conformance-matrix:end -->"
ORDER = {"chromium": 0, "webkit": 1}
ROLE = {"chromium": "macOS default", "webkit": "iOS/iPadOS; macOS fallback"}
SYMBOL = {"passed": "✅", "failed": "❌", "unsupported": "➖", "engineUnavailable": "⬜"}


def cell(outcome: dict) -> str:
    kind = next(iter(outcome))
    if kind == "unsupported":
        caps = outcome[kind].get("_0", [])
        return f"➖ needs {', '.join(caps)}"
    if kind == "failed":
        return "❌ fails"
    return SYMBOL[kind]


def render() -> str:
    reports = sorted((json.loads(p.read_text()) for p in REPORTS.glob("*.json")), key=lambda r: ORDER.get(r["engineID"], 9))
    if not reports:
        sys.exit("no reports in build/conformance — run `make conformance` first")
    head = "| Case | " + " | ".join(f"{r['engineName']} ({ROLE.get(r['engineID'], '')})" for r in reports) + " |"
    rows = [head, "|---" * (len(reports) + 1) + "|"]
    for i, result in enumerate(reports[0]["results"]):
        cells = [cell(r["results"][i]["outcome"]) for r in reports]
        rows.append(f"| **{result['caseID']}** {result['title']} | " + " | ".join(cells) + " |")
    legend = "✅ passes · ❌ fails · ➖ engine doesn't declare the capability · ⬜ engine not available on this build yet"
    # No engine versions here: they differ per machine (e.g. WebKit ships with the OS), and the
    # committed matrix must be reproducible anywhere. Versions are in build/conformance/*.json.
    return "\n".join([BEGIN, f"_Generated by `make conformance` from `EngineConformance` results. {legend}._", "",
                      *rows, END])


def main() -> int:
    text = CHECKLIST.read_text()
    start, end = text.index(BEGIN), text.index(END) + len(END)
    updated = text[:start] + render() + text[end:]
    if "--check" in sys.argv:
        if updated != text:
            print("✘ checklists/005 matrix is stale: run `make conformance`", file=sys.stderr)
            return 1
        print("✔ engine matrix up to date")
        return 0
    CHECKLIST.write_text(updated)
    print(f"✔ rendered engine matrix into {CHECKLIST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
