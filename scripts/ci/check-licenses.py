"""License compliance (PRV-003, REL-016).

1. Nera is MPL-2.0 (LICENSE; ADR-0005).
2. Every third-party dependency (SwiftPM `.package(...)` entries, and the CEF binary) must be
   listed in scripts/ci/data/dependencies.json with a reviewed SPDX license on the allowlist.
3. No GPL/AGPL/LGPL/SSPL license text inside Nera's own sources, which stay MPL-2.0 file by file (ADR-0005).
4. THIRD_PARTY_NOTICES.md is generated from dependencies.json and must be up to date (--write to regenerate).
"""
from __future__ import annotations

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DEPS = ROOT / "scripts" / "ci" / "data" / "dependencies.json"
NOTICES = ROOT / "THIRD_PARTY_NOTICES.md"
ALLOWED = {"Apache-2.0", "MIT", "BSD-2-Clause", "BSD-3-Clause", "ISC", "Zlib", "Unicode-3.0", "MPL-2.0", "BSL-1.0"}
COPYLEFT = re.compile(r"GNU (Affero |Lesser )?General Public License|\bSSPL\b|Server Side Public License", re.I)
SOURCES = ["Packages/NeraKit/Sources", "Apps"]


def render_notices(deps: list[dict]) -> str:
    lines = ["# Third-party notices", "", "Generated by `scripts/ci/check-licenses.py --write` from `scripts/ci/data/dependencies.json`.", ""]
    if not deps:
        lines += ["Nera currently ships **no third-party code**. It uses only Apple system frameworks.", ""]
    for d in sorted(deps, key=lambda d: d["name"].lower()):
        lines += [f"## {d['name']} {d.get('version', '')}".rstrip(), "", f"- License: {d['license']}", f"- Source: {d['source']}",
                  f"- Used for: {d['purpose']}", ""]
    return "\n".join(lines)


def main() -> int:
    errors: list[str] = []
    license_text = (ROOT / "LICENSE").read_text()
    if not license_text.startswith("Mozilla Public License Version 2.0"):
        errors.append("LICENSE isn't the MPL-2.0 text (ADR-0005)")

    deps = json.loads(DEPS.read_text())["dependencies"]
    reviewed = {d["name"].lower(): d for d in deps}
    for d in deps:
        if d["license"] not in ALLOWED:
            errors.append(f"{d['name']}: license {d['license']} is not on the allowlist {sorted(ALLOWED)}")
        for key in ("name", "license", "source", "purpose", "reviewedBy"):
            if not d.get(key):
                errors.append(f"{d.get('name', '?')}: missing '{key}' in dependencies.json")

    for manifest in ROOT.glob("Packages/*/Package.swift"):
        for url in re.findall(r'\.package\(\s*(?:name:\s*"[^"]*",\s*)?url:\s*"([^"]+)"', manifest.read_text()):
            name = url.rstrip("/").removesuffix(".git").rsplit("/", 1)[-1].lower()
            if name not in reviewed:
                errors.append(f"{manifest.relative_to(ROOT)}: dependency {url} has no license review in dependencies.json")

    for base in SOURCES:
        for f in (ROOT / base).rglob("*"):
            if f.is_file() and f.suffix in {".swift", ".h", ".m", ".mm", ".c", ".cc", ".cpp"} and COPYLEFT.search(f.read_text(errors="ignore")):
                errors.append(f"{f.relative_to(ROOT)}: contains copyleft license text")

    expected = render_notices(deps)
    if "--write" in sys.argv:
        NOTICES.write_text(expected)
        print(f"✔ wrote {NOTICES.name}")
    elif not NOTICES.exists() or NOTICES.read_text() != expected:
        errors.append("THIRD_PARTY_NOTICES.md is stale: run scripts/ci/check-licenses.py --write")

    for e in errors:
        print(f"✘ {e}", file=sys.stderr)
    if errors:
        return 1
    print(f"✔ licenses OK (Nera MPL-2.0; {len(deps)} third-party dependencies reviewed)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
