# Fetches + verifies the pinned CEF, builds its wrapper library (both cached outside the repo), and writes
# build/cef.xcconfig so the Xcode project finds them. Run by `make project` and CI before xcodegen.
set -euo pipefail
cd "$(dirname "$0")/../.."
CEF_ROOT="$(scripts/engine/fetch-cef.sh)"
CEF_BUILD="$(scripts/engine/build-cef-wrapper.sh "$CEF_ROOT")"
mkdir -p build
cat > build/cef.xcconfig <<XC
// Generated by scripts/engine/prepare-cef.sh — not committed.
CEF_ROOT = $CEF_ROOT
CEF_WRAPPER_DIR = $CEF_BUILD/libcef_dll_wrapper
XC
echo "✔ CEF ready: $CEF_ROOT" >&2
